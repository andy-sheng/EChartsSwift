// PORT-NOTE: upstream `extends ComponentModel` and `implements AxisBaseModel` (a TS interface that
//   declaration-merges ComponentModel + AxisModelCommonMixin + AxisModelExtendedInCreator + `axis`).
//   Per CONVENTIONS §2, mixins are ported as protocol + protocol-extension: the class extends the real
//   `ComponentModel` reference type and conforms to the `AxisModelCommonMixin` protocol (which supplies
//   `needIncludeZero()` / `getCoordSysModel()` via its extension — this replaces
//   `zrUtil.mixin(CartesianAxisModel, AxisModelCommonMixin)` below). The `axis` member is declared here.
//   `AxisModelExtendedInCreator` (getCategories / getOrdinalMeta / updateAxisBreaks) is NOT implemented
//   on this class in upstream either — those come from the subclass generated by `axisModelCreator`
