// PORT-NOTE: not `final` — upstream subclasses it (passed as `BaseAxisModelClass` to
//   `axisModelCreator`; the generated per-type axis model extends it). Per CONVENTIONS §2, reference
//   types that are subclassed upstream stay open to subclassing.
// PORT-NOTE (INTEGRATION): upstream `class CartesianAxisModel extends ComponentModel implements
//   AxisBaseModel<CartesianAxisOption>`. `AxisBaseModel` is a TS interface (structural), but the Swift
//   port models it as a real `open class AxisBaseModel: ComponentModel, AxisModelCommonMixin`. Since
//   `Axis.model` is typed `AxisBaseModel` and consumers (Grid, axisHelper.isAxisOnBand) require it,
//   `CartesianAxisModel` subclasses `AxisBaseModel` here (inheriting ComponentModel + the
//   AxisModelCommonMixin conformance + the `axis` slot). The former standalone `_axis`/`axis` members
//   are removed in favor of the base class ones.
public class CartesianAxisModel: AxisBaseModel {

    // static type = 'cartesian2dAxis';
    public override class var type: ComponentFullType { return "cartesian2dAxis" }

    // getCoordSysModel(): GridModel {
    //     return this.getReferringComponents('grid', SINGLE_REFERRING).models[0] as GridModel;
    // }
    //
    // PORT-NOTE: upstream returns `GridModel` (ported at coord/cartesian/GridModel.swift); the
    //   `AxisModelCommonMixin.getCoordSysModel()` protocol requirement returns `Any?` (Swift protocol
    //   witnesses can't narrow the return), so `models[0]` (a `ComponentModel`) is returned as-is and
    //   callers cast to `GridModel` at the use site (e.g. CartesianAxisView).
    public func getCoordSysModel() -> Any? {
        return self.getReferringComponents("grid", model.SINGLE_REFERRING).models[0]
    }

}

